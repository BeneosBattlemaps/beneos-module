/**
 * Beneos Native Battlemap Installer (Plan §18.7 final, parallel to legacy
 * Moulinette path).
 *
 * Engine that owns the entire download + import pipeline without using
 * scene-packer's MoulinetteImporter. Drives a BeneosBattlemapInstallProgress
 * window for the user-facing UI. Replaces the 3 cloud-scope-buttons; the
 * Moulinette-Legacy button stays as a search-UI fallback for non-cloud maps.
 *
 * Pipeline:
 *   1. get_packinfo: list of every file in the pack with signed URLs
 *   2. Asset download: every "data/assets/<path>" file is fetched and uploaded
 *      to <path> under the user's data root (Forge: forgevtt source).
 *   3. Document create: parse "data/<Type>.json", call <Type>.createDocuments()
 *      in the standard Foundry order (Folders, Scene, Actor, JournalEntry,
 *      Item, Macro, Playlist, Cards, RollTable).
 *
 * V1 simplifications:
 *   - Compendium-ref rewriting is skipped. Inter-doc references in journals
 *     may point at compendium docs that don't exist in this world. Visible
 *     as "broken link" in the journal but no crash.
 *   - Existing documents (same _id) are SKIPPED rather than overwritten.
 *   - Scene thumbnails are auto-regenerated by Foundry on first scene-open.
 *   - System-mismatch check is skipped (we trust the user).
 *   - No retry/range-resume (V2).
 */

const FOUNDRY_DOC_TYPES_IN_ORDER = [
  // [doc-collection-name, document-class-getter]
  ["folders",       () => globalThis.Folder],
  ["scenes",        () => globalThis.Scene],
  ["actors",        () => globalThis.Actor],
  ["journal",       () => globalThis.JournalEntry],
  ["items",         () => globalThis.Item],
  ["macros",        () => globalThis.Macro],
  ["playlists",     () => globalThis.Playlist],
  ["cards",         () => globalThis.Cards],
  ["tables",        () => globalThis.RollTable],
]

const JSON_FILE_TO_PHASE = {
  "data/folders.json":      { phaseKey: "data",       collection: "folders",   docClass: () => globalThis.Folder },
  "data/Scene.json":        { phaseKey: "scenes",     collection: "scenes",    docClass: () => globalThis.Scene },
  "data/Actor.json":        { phaseKey: "actors",     collection: "actors",    docClass: () => globalThis.Actor },
  "data/JournalEntry.json": { phaseKey: "journals",   collection: "journal",   docClass: () => globalThis.JournalEntry },
  "data/Item.json":         { phaseKey: "items",      collection: "items",     docClass: () => globalThis.Item },
  "data/Macro.json":        { phaseKey: "macros",     collection: "macros",    docClass: () => globalThis.Macro },
  "data/Playlist.json":     { phaseKey: "playlists",  collection: "playlists", docClass: () => globalThis.Playlist },
  "data/Cards.json":        { phaseKey: "cards",      collection: "cards",     docClass: () => globalThis.Cards },
  "data/RollTable.json":    { phaseKey: "rolltables", collection: "tables",    docClass: () => globalThis.RollTable },
}

export class BeneosNativeBattlemapInstaller {

  constructor({ packageId, label = "", coverUrl = null } = {}) {
    if (!packageId) throw new Error("BeneosNativeBattlemapInstaller: packageId is required")
    this.packageId = packageId
    this.label     = label || packageId
    this.coverUrl  = coverUrl
    this.progress  = null
  }

  /** One-shot install + UI. Returns the progress window so callers can wait if needed. */
  static async install({ packageId, label, coverUrl } = {}) {
    const inst = new BeneosNativeBattlemapInstaller({ packageId, label, coverUrl })
    return inst.run()
  }

  async run() {
    const ProgressWindow = globalThis.BeneosBattlemapInstallProgress
    if (!ProgressWindow) throw new Error("BeneosBattlemapInstallProgress not loaded")

    this.progress = await ProgressWindow.open({
      label:     this.label,
      coverUrl:  this.coverUrl,
      packageId: this.packageId,
    })

    try {
      // Phase: load manifest + system + data (we collapse them into one
      // "loading data" step since the native installer doesn't need a
      // separate manifest fetch).
      this.progress.handleStatusMessage("Loading manifest and pack contents")
      const mgr = window.BeneosScenePacker
      if (!mgr) throw new Error("BeneosScenePackerManager missing")
      const packInfo = await mgr.getPackInfo(this.packageId)

      // Phase: classify + download all binary assets
      this.progress.handleStatusMessage("Preparing asset download")
      const { assets, jsons, mtteJson } = this.#classifyPack(packInfo)

      await this.#downloadAssets(assets)

      // Phase: create documents in Foundry order
      await this.#importDocuments(jsons, mtteJson)

      this.progress.markCompleted()
    } catch (err) {
      console.error("BeneosNativeBattlemapInstaller | failure", err)
      this.progress.markFailed(err?.message || String(err))
      throw err
    }
    return this.progress
  }

  /**
   * Split the packInfo URL map into:
   *   - assets: binary files under data/assets/* that need uploading
   *   - jsons:  document-collection JSON files we'll parse + createDocuments()
   *   - mtteJson: the scene-packer pack descriptor (informational only here)
   */
  #classifyPack(packInfo) {
    const assets = []
    const jsons  = {}
    let mtteJson = null
    for (const [relPath, url] of Object.entries(packInfo)) {
      if (relPath === "mtte.json") { mtteJson = url; continue }
      if (relPath === "beneos-pack-manifest.json") continue
      if (relPath.startsWith("data/assets/")) {
        // Strip "data/assets/" -> client-side relative path under user's data root.
        const target = relPath.substring("data/assets/".length)
        assets.push({ url, target, relPath })
        continue
      }
      if (relPath.startsWith("data/") && relPath.endsWith(".json")) {
        jsons[relPath] = url
        continue
      }
      if (relPath.startsWith("data/scenes/thumbs/")) {
        // Thumbnails skipped — Foundry regenerates on first scene open.
        continue
      }
      if (relPath.startsWith("data/cover/")) {
        // Pack cover is already shown by the install window hero; no local copy needed.
        continue
      }
      // Anything else (e.g. root-level slug.json from scene-packer export) skipped.
    }
    return { assets, jsons, mtteJson }
  }

  /**
   * Fetch + upload each binary asset under the user's data root. Uses Foundry's
   * FilePicker.implementation.upload(); auto-detects Forge to upload to the
   * Assets Library instead of the Data store (per hosting brief).
   */
  async #downloadAssets(assets) {
    this.progress.handleStatusMessage("Downloading scene assets")
    const FilePicker = foundry.applications?.apps?.FilePicker?.implementation ?? globalThis.FilePicker
    const isForge = typeof ForgeVTT !== "undefined" && ForgeVTT.usingTheForge === true
    const source  = isForge ? "forgevtt" : "data"

    const total = assets.length
    for (let i = 0; i < total; i++) {
      const a = assets[i]
      try {
        // Ensure the target directory exists before upload. FilePicker.browse()
        // throws on missing dir; we mkdir-p via createDirectory().
        const dir  = a.target.includes("/") ? a.target.substring(0, a.target.lastIndexOf("/")) : ""
        const file = a.target.substring(a.target.lastIndexOf("/") + 1)
        if (dir) await this.#ensureDir(FilePicker, source, dir)

        // fetch the asset bytes, wrap as File, upload.
        const resp = await fetch(a.url)
        if (!resp.ok) throw new Error(`HTTP ${resp.status} for ${a.target}`)
        const blob = await resp.blob()
        const fileObj = new File([blob], file, { type: blob.type })
        await FilePicker.upload(source, dir, fileObj, {}, { notify: false })
      } catch (err) {
        console.warn("BeneosNativeInstaller | asset upload failed", a.target, err)
        // V1: continue on per-asset failure so the document phase still runs.
        // V2: collect failures, mark phase as error if too many.
      }
      this.progress.handleAssetProgress("Assets", total, i + 1)
    }
  }

  /**
   * Recursively create directories under (source, dir). Foundry's FilePicker
   * does not have an explicit mkdir-p; createDirectory() handles one level
   * and is idempotent (no-op if the dir exists).
   */
  async #ensureDir(FilePicker, source, dir) {
    if (!dir) return
    const parts = dir.split("/").filter(Boolean)
    let path = ""
    for (const p of parts) {
      path = path ? `${path}/${p}` : p
      try {
        await FilePicker.createDirectory(source, path, {})
      } catch (e) {
        // Directory exists — ignore. Other errors logged but don't abort.
        const msg = String(e?.message || e)
        if (!/exists/i.test(msg) && !/eexist/i.test(msg)) {
          console.debug("BeneosNativeInstaller | createDirectory", path, msg)
        }
      }
    }
  }

  /**
   * Parse each document-collection JSON and call createDocuments() in the
   * Foundry-imposed order (Folders first so other docs can reference them).
   * Skip documents whose _id already exists in the world (idempotency).
   *
   * Iteration order MUST be folders-first — otherwise Foundry silently drops
   * scene/actor/journal folder references and lands them in root. We
   * enumerate JSON_FILE_TO_PHASE explicitly instead of Object.entries(jsons)
   * because the latter is alphabetical and Scene.json (capital S) sorts
   * before folders.json (lowercase f).
   */
  async #importDocuments(jsons, _mtteJsonUrl) {
    const ORDERED_PATHS = [
      "data/folders.json",
      "data/Scene.json",
      "data/Actor.json",
      "data/JournalEntry.json",
      "data/Item.json",
      "data/Macro.json",
      "data/Playlist.json",
      "data/Cards.json",
      "data/RollTable.json",
    ]
    for (const relPath of ORDERED_PATHS) {
      const url = jsons[relPath]
      if (!url) continue
      const meta = JSON_FILE_TO_PHASE[relPath]
      if (!meta) continue
      const docClass = meta.docClass()
      if (!docClass || typeof docClass.createDocuments !== "function") {
        console.warn("BeneosNativeInstaller | doc class missing for", relPath)
        continue
      }
      this.progress.handleStatusMessage(`Importing ${meta.phaseKey}`)
      let raw
      try {
        const resp = await fetch(url)
        if (!resp.ok) throw new Error(`HTTP ${resp.status}`)
        raw = await resp.json()
      } catch (err) {
        console.warn(`BeneosNativeInstaller | could not fetch ${relPath}`, err)
        continue
      }
      // scene-packer's export format varies per type:
      //   - Scene.json, Actor.json, Item.json, etc. → Array of documents
      //   - folders.json → Object keyed by _id
      // Normalise to an array so createDocuments() gets the right shape.
      let arr
      if (Array.isArray(raw)) arr = raw
      else if (raw && typeof raw === "object") arr = Object.values(raw)
      else arr = []
      if (arr.length === 0) continue

      // Idempotency: drop entries whose _id already exists in the target collection.
      const coll = game[meta.collection]
      const filtered = arr.filter(d => {
        if (!d?._id) return true
        return !coll?.get?.(d._id)
      })
      if (filtered.length === 0) {
        this.progress.handleAssetProgress(meta.phaseKey, arr.length, arr.length)
        continue
      }
      try {
        await docClass.createDocuments(filtered, { keepId: true })
      } catch (err) {
        console.warn(`BeneosNativeInstaller | createDocuments failed for ${relPath}`, err)
        // Partial fall-back: try inserting one at a time so a single bad doc
        // doesn't sink the rest of the batch.
        let ok = 0
        for (const d of filtered) {
          try {
            await docClass.createDocuments([d], { keepId: true })
            ok++
          } catch (e2) {
            console.warn(`BeneosNativeInstaller | doc create skipped (${d?._id})`, e2?.message || e2)
          }
          this.progress.handleAssetProgress(meta.phaseKey, filtered.length, ok)
        }
      }
      this.progress.handleAssetProgress(meta.phaseKey, arr.length, arr.length)
    }
  }
}

// Expose globally so the cloud-window handler can route to it without an
// import cycle (cloud-window-v2.mjs loads ESM-only too).
globalThis.BeneosNativeBattlemapInstaller = BeneosNativeBattlemapInstaller
